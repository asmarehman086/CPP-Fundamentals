#include <iostream>
using namespace std;

int main() {
    int integerValue = 10;
    float floatValue = 3.14f;
    double doubleValue = 99.99;
    char grade = 'A';
    bool isPassed = true;

    cout << "Integer: " << integerValue << endl;
    cout << "Float: " << floatValue << endl;
    cout << "Double: " << doubleValue << endl;
    cout << "Character: " << grade << endl;
    cout << "Boolean: " << isPassed << endl;

    return 0;
}